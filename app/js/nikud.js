/* תווי ניקוד — בלי המקף העברי ־ (U+05BE) שמשמש בשורשים כמו ב־נ־ה */
const NIKUD_MARKS = /[֑-ֽֿ-ׇ]/g;

/* מוסיף ניקוד לטקסט, מילה־מילה. שומר פיסוק בקצוות. */
function nikkudize(text) {
  if (!text) return text;
  return text.split(/(\s+)/).map(token => {
    if (!token.trim()) return token;
    const m = token.match(/^([^א-ת]*)([א-ת֑-ׇ־]+)([^א-ת]*)$/);
    if (!m) return token;
    const voc = NIKUD_WORDS[m[2]];
    return voc ? m[1] + voc + m[3] : token;
  }).join('');
}

/* מחזיר טקסט ללא ניקוד */
function denikkudize(text) {
  return text.replace(NIKUD_MARKS, '');
}

/* החלה / הסרה על כל צומתי הטקסט בעץ נתון */
function applyNikudToDom(root, on) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    node.nodeValue = on ? nikkudize(denikkudize(node.nodeValue)) : denikkudize(node.nodeValue);
  }
}

/* רענון לפי מצב שמור — נקרא אחרי כל רינדור */
function refreshNikud() {
  if (typeof S === 'undefined') return;
  applyNikudToDom(document.getElementById('unit-card'), S.nikud);
  applyNikudToDom(document.querySelector('.unit-side'), S.nikud);
}

/* עוזר לטקסט שנוצר דינמית (מילים בארקייד, מילת ההאכלה, טוסטים) */
function NK(text) {
  return (typeof S !== 'undefined' && S.nikud) ? nikkudize(text) : text;
}
